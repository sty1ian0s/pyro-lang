const std = @import("std");

/// Directories whose `.zig` files `zig build test` discovers automatically.
/// Each tree compiles as one module rooted at the tree, so files may import
/// any other file in the same tree with a relative path.
const test_trees = [_][]const u8{ "stage0/src", "runtime", "tools" };

pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});
    const llvm = b.option(bool, "llvm", "Link LLVM (llvm-config on PATH) for the LLVM backend") orelse false;

    const build_options = b.addOptions();
    build_options.addOption(bool, "llvm", llvm);
    const common: Common = .{
        .build_options = build_options,
        .llvm = if (llvm) Llvm.query(b) else null,
    };

    // --- pyro executable ----------------------------------------------------
    const exe_mod = b.createModule(.{
        .root_source_file = b.path("stage0/src/main.zig"),
        .target = target,
        .optimize = optimize,
    });
    addCommonImports(b, exe_mod, common);

    const exe = b.addExecutable(.{ .name = "pyro", .root_module = exe_mod });
    b.installArtifact(exe);

    const run_cmd = b.addRunArtifact(exe);
    run_cmd.addPassthruArgs();
    b.step("run", "Build and run pyro").dependOn(&run_cmd.step);

    // --- zig build test: auto-discovered test trees --------------------------
    const test_step = b.step("test", "Run all unit tests (auto-discovered)");
    for (test_trees) |tree| {
        const files = discoverZigFiles(b, tree);
        if (files.len == 0) continue;

        // Copy the tree next to a generated root that imports every file, so the
        // module root is the tree itself and cross-directory imports work.
        const wf = b.addWriteFiles();
        _ = wf.addCopyDirectory(b.path(tree), "", .{});
        var src: std.ArrayList(u8) = .empty;
        src.appendSlice(b.allocator, "// Generated by build.zig: imports every file in the tree.\ncomptime {\n") catch @panic("OOM");
        for (files) |f| src.print(b.allocator, "    _ = @import(\"{s}\");\n", .{f}) catch @panic("OOM");
        src.appendSlice(b.allocator, "}\n") catch @panic("OOM");
        const root = wf.add("pyro_test_root.zig", src.items);

        const test_mod = b.createModule(.{
            .root_source_file = root,
            .target = target,
            .optimize = optimize,
        });
        addCommonImports(b, test_mod, common);
        addTreeOptions(b, tree, test_mod);
        const name = b.fmt("test-{s}", .{tree});
        std.mem.replaceScalar(u8, name, '/', '-');
        const t = b.addTest(.{ .name = name, .root_module = test_mod });
        test_step.dependOn(&b.addRunArtifact(t).step);
    }

    // --- zig build conformance ------------------------------------------------
    // Runs tools/conformance/main.zig as `<harness> <pyro> <conformance dir> [args...]`.
    // Until that file exists, a stub prints a note and succeeds.
    const harness_src = if (fileExists(b, "tools/conformance/main.zig"))
        b.path("tools/conformance/main.zig")
    else
        b.addWriteFiles().add("conformance_stub.zig",
            \\const std = @import("std");
            \\pub fn main() void {
            \\    std.debug.print("conformance: tools/conformance/main.zig not present yet (T004); nothing to run\n", .{});
            \\}
            \\
        );
    const harness = b.addExecutable(.{
        .name = "pyro-conformance",
        .root_module = b.createModule(.{
            .root_source_file = harness_src,
            .target = b.graph.host,
            .optimize = optimize,
        }),
    });
    const run_conf = b.addRunArtifact(harness);
    run_conf.addArtifactArg(exe);
    run_conf.addDirectoryArg(b.path("conformance"));
    run_conf.addPassthruArgs();
    b.step("conformance", "Run the conformance suite (B.9)").dependOn(&run_conf.step);
}

/// Returns the sorted tree-relative paths (with '/') of every `.zig` file under
/// `tree`, skipping `testdata` directories. Registers each directory as a
/// configure dependency so adding or removing a file re-runs discovery.
fn discoverZigFiles(b: *std.Build, tree: []const u8) []const []const u8 {
    const io = b.graph.io;
    const arena = b.allocator;
    b.dependOnDirectoryContents(b.path(tree));

    var dir = b.root.root_dir.handle.openDir(io, b.pathJoin(&.{ b.root.sub_path, tree }), .{ .iterate = true }) catch return &.{};
    defer dir.close(io);
    var walker = dir.walk(arena) catch @panic("OOM");
    defer walker.deinit();

    var files: std.ArrayList([]const u8) = .empty;
    while (walker.next(io) catch |err| std.debug.panic("walking {s}: {t}", .{ tree, err })) |entry| {
        const rel = arena.dupe(u8, entry.path) catch @panic("OOM");
        std.mem.replaceScalar(u8, rel, std.fs.path.sep, '/');
        switch (entry.kind) {
            .directory => b.dependOnDirectoryContents(b.path(b.pathJoin(&.{ tree, rel }))),
            .file => if (std.mem.endsWith(u8, rel, ".zig") and !inTestdata(rel))
                files.append(arena, rel) catch @panic("OOM"),
            else => {},
        }
    }
    std.mem.sort([]const u8, files.items, {}, lessThan);
    return files.items;
}

fn inTestdata(rel: []const u8) bool {
    var it = std.mem.splitScalar(u8, rel, '/');
    while (it.next()) |part| if (std.mem.eql(u8, part, "testdata")) return true;
    return false;
}

fn lessThan(_: void, a: []const u8, b: []const u8) bool {
    return std.mem.lessThan(u8, a, b);
}

fn fileExists(b: *std.Build, sub_path: []const u8) bool {
    // The parent directory is already a configure dependency via discoverZigFiles("tools").
    b.root.root_dir.handle.access(b.graph.io, b.pathJoin(&.{ b.root.sub_path, sub_path }), .{}) catch return false;
    return true;
}

const Common = struct {
    build_options: *std.Build.Step.Options,
    llvm: ?Llvm,
};

/// EDIT POINT: imports and link settings shared by the `pyro` executable and
/// every test tree module. T003 adds its one `m.addImport("diag_codes", ...)`
/// line here (generator logic lives in a T003-owned file under `stage0/build/`).
fn addCommonImports(b: *std.Build, m: *std.Build.Module, c: Common) void {
    _ = b;
    m.addOptions("build_options", c.build_options);
    if (c.llvm) |l| l.link(m);
}

/// EDIT POINT: per-tree settings for the test module of `tree`.
/// T010 adds its C harness wiring to the `runtime` branch.
fn addTreeOptions(b: *std.Build, tree: []const u8, m: *std.Build.Module) void {
    if (std.mem.eql(u8, tree, "runtime")) {
        m.link_libc = true; // runtime tests call libc (getpid, abort paths)
        // T010: C harness that calls pyro_rt_trap through the C ABI.
        m.addCSourceFile(.{ .file = b.path("runtime/trap_harness.c") });
        // T010: lets runtime/trap.zig @embedFile the prelude TrapKind to check the mirror.
        m.addAnonymousImport("trap.pr", .{ .root_source_file = b.path("std/core/trap.pr") });
    }
}

/// `llvm-config` output, queried once. Only used with -Dllvm=true.
const Llvm = struct {
    libdir: []const u8,
    includedir: []const u8,
    libs: []const u8,

    fn query(b: *std.Build) Llvm {
        b.graph.poisonCache(); // llvm-config output is not tracked by the configure cache
        return .{
            .libdir = std.mem.trim(u8, b.run(&.{ "llvm-config", "--libdir" }), " \r\n"),
            .includedir = std.mem.trim(u8, b.run(&.{ "llvm-config", "--includedir" }), " \r\n"),
            .libs = b.run(&.{ "llvm-config", "--libs" }),
        };
    }

    fn link(l: Llvm, m: *std.Build.Module) void {
        m.addLibraryPath(.{ .cwd_relative = l.libdir });
        m.addSystemIncludePath(.{ .cwd_relative = l.includedir });
        var it = std.mem.tokenizeAny(u8, l.libs, " \r\n");
        while (it.next()) |flag| {
            if (std.mem.startsWith(u8, flag, "-l")) m.linkSystemLibrary(flag[2..], .{});
        }
        m.link_libc = true;
        m.link_libcpp = true;
    }
};
