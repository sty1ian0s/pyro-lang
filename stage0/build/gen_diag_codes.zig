//! Build-time generator for the `diag_codes` module.
//!
//! Usage: `gen_diag_codes <out.zig> <A-diagnostics.md> <impl_warnings.md>`
//!
//! Reads every table row whose first cell is a code (`| E0310 | meaning | § |`)
//! from the A.3 registry of the spec and from the implementation-warning list,
//! and writes a Zig file declaring `DiagCode`. Fails on duplicate or malformed
//! codes, on `W9xxx` codes in the spec, and on anything but `W9xxx` in the
//! implementation list.

const std = @import("std");

const Row = struct { code: []const u8, meaning: []const u8 };

pub fn main(init: std.process.Init) !void {
    const arena = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(arena);
    if (args.len != 4) std.process.fatal("usage: gen_diag_codes <out.zig> <A-diagnostics.md> <impl_warnings.md>", .{});

    var rows: std.ArrayList(Row) = .empty;
    try collect(arena, io, args[2], .spec, &rows);
    try collect(arena, io, args[3], .impl, &rows);

    var out: std.ArrayList(u8) = .empty;
    try out.appendSlice(arena,
        \\//! Generated by stage0/build/gen_diag_codes.zig from spec/A-diagnostics.md (A.3)
        \\//! and stage0/build/impl_warnings.md. Do not edit.
        \\
        \\/// Every diagnostic code in the registry. Tag names are the codes as written
        \\/// (`.E0332`), so using a code that is not in the registry fails to compile.
        \\/// The value is the code number, plus 10000 for `W` codes.
        \\pub const DiagCode = enum(u16) {
        \\
    );
    for (rows.items) |r| try out.print(arena, "    {s} = {d},\n", .{ r.code, value(r.code) });
    try out.appendSlice(arena,
        \\
        \\    /// True for `W` codes (warnings), false for `E` codes (errors).
        \\    pub fn isWarning(c: DiagCode) bool {
        \\        return @intFromEnum(c) >= 10000;
        \\    }
        \\
        \\    /// The registry's "Meaning" column, verbatim (Markdown backticks kept).
        \\    pub fn meaning(c: DiagCode) []const u8 {
        \\        return switch (c) {
        \\
    );
    for (rows.items) |r| try out.print(arena, "            .{s} => \"{f}\",\n", .{ r.code, std.zig.fmtString(r.meaning) });
    try out.appendSlice(arena,
        \\        };
        \\    }
        \\};
        \\
    );
    try std.Io.Dir.cwd().writeFile(io, .{ .sub_path = args[1], .data = out.items });
}

fn collect(arena: std.mem.Allocator, io: std.Io, path: []const u8, source: enum { spec, impl }, rows: *std.ArrayList(Row)) !void {
    const text = try std.Io.Dir.cwd().readFileAlloc(io, path, arena, .limited(1 << 20));
    var lines = std.mem.splitScalar(u8, text, '\n');
    var line_no: usize = 0;
    var found: usize = 0;
    while (lines.next()) |raw| {
        line_no += 1;
        const line = std.mem.trim(u8, raw, " \t\r");
        if (!std.mem.startsWith(u8, line, "|")) continue;
        var cells = std.mem.splitScalar(u8, line[1..], '|');
        const code = std.mem.trim(u8, cells.first(), " ");
        if (code.len == 0 or (code[0] != 'E' and code[0] != 'W')) continue; // header or separator row
        // Exactly 4 ASCII digits: parseInt alone would also accept `_` separators.
        if (code.len != 5 or !allDigits(code[1..]))
            std.process.fatal("{s}:{d}: malformed code '{s}'", .{ path, line_no, code });
        const impl_range = code[0] == 'W' and code[1] == '9';
        if (impl_range != (source == .impl))
            std.process.fatal("{s}:{d}: {s}: W9xxx codes belong in impl_warnings.md and only there", .{ path, line_no, code });
        for (rows.items) |r| if (std.mem.eql(u8, r.code, code))
            std.process.fatal("{s}:{d}: duplicate code {s}", .{ path, line_no, code });
        const meaning = std.mem.trim(u8, cells.next() orelse "", " ");
        if (meaning.len == 0) std.process.fatal("{s}:{d}: {s} has no meaning", .{ path, line_no, code });
        try rows.append(arena, .{ .code = code, .meaning = meaning });
        found += 1;
    }
    if (source == .spec and found == 0) std.process.fatal("{s}: no A.3 registry rows found", .{path});
}

fn allDigits(s: []const u8) bool {
    for (s) |ch| if (!std.ascii.isDigit(ch)) return false;
    return true;
}

fn value(code: []const u8) u16 {
    const n = std.fmt.parseInt(u16, code[1..], 10) catch unreachable;
    return if (code[0] == 'W') 10000 + n else n;
}
