//! A.3 coverage: which registry codes have at least one passing and one failing
//! case (B.9). A failing case for a code expects it with `//~`; a passing case
//! names it with `//@ covers:`.

const std = @import("std");
const Allocator = std.mem.Allocator;
const Writer = std.Io.Writer;
const isCode = @import("case.zig").isCode;

pub const Coverage = struct {
    /// Registry codes in spec order.
    codes: []const []const u8,
    pass: []u32,
    fail: []u32,

    /// Makes an all-zero coverage table for `codes`.
    pub fn init(arena: Allocator, codes: []const []const u8) !Coverage {
        const pass = try arena.alloc(u32, codes.len);
        const fail = try arena.alloc(u32, codes.len);
        @memset(pass, 0);
        @memset(fail, 0);
        return .{ .codes = codes, .pass = pass, .fail = fail };
    }

    /// Counts one case. Codes outside the registry (e.g. `W9xxx`) are ignored.
    pub fn add(c: Coverage, counts: []u32, code: []const u8) void {
        for (c.codes, 0..) |reg, i| if (std.mem.eql(u8, reg, code)) {
            counts[i] += 1;
            return;
        };
    }

    /// Number of codes lacking a passing or a failing case.
    pub fn lacking(c: Coverage) usize {
        var n: usize = 0;
        for (c.pass, c.fail) |p, f| n += @intFromBool(p == 0 or f == 0);
        return n;
    }

    /// Writes the summary line and every code lacking a passing or failing case.
    pub fn writeLacking(c: Coverage, w: *Writer) Writer.Error!void {
        try w.print("coverage: {d} of {d} A.3 codes lack a passing or failing case\n", .{ c.lacking(), c.codes.len });
        for (c.codes, c.pass, c.fail) |code, p, f| {
            if (p != 0 and f != 0) continue;
            const what = if (p == 0 and f == 0) "pass, fail" else if (p == 0) "pass" else "fail";
            try w.print("  {s}  missing {s}\n", .{ code, what });
        }
    }

    /// Writes the full table as Markdown (for `--coverage-out`).
    pub fn writeMarkdown(c: Coverage, w: *Writer) Writer.Error!void {
        try w.writeAll("# A.3 conformance coverage\n\nGenerated by `zig build conformance -- --coverage-out <file>`.\n\n");
        try w.print("{d} of {d} codes lack a passing or failing case.\n\n| Code | Pass | Fail |\n|------|------|------|\n", .{ c.lacking(), c.codes.len });
        for (c.codes, c.pass, c.fail) |code, p, f| try w.print("| {s} | {d} | {d} |\n", .{ code, p, f });
    }
};

/// Extracts the codes of the A.3 registry tables from `spec/A-diagnostics.md`:
/// the first cell of each table row between `## A.3` and the next `## ` heading.
pub fn parseRegistry(arena: Allocator, markdown: []const u8) ![]const []const u8 {
    var codes: std.ArrayList([]const u8) = .empty;
    var in_a3 = false;
    var lines = std.mem.splitScalar(u8, markdown, '\n');
    while (lines.next()) |line| {
        if (std.mem.startsWith(u8, line, "## ")) {
            in_a3 = std.mem.startsWith(u8, line, "## A.3");
            continue;
        }
        if (!in_a3) continue;
        const row = std.mem.cutPrefix(u8, line, "|") orelse continue;
        const cell, _ = std.mem.cutScalar(u8, row, '|') orelse continue;
        const code = std.mem.trim(u8, cell, " ");
        if (isCode(code)) try codes.append(arena, code);
    }
    return codes.items;
}

test "registry parse and lacking report" {
    var arena: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena.deinit();
    const codes = try parseRegistry(arena.allocator(),
        \\## A.2 Format
        \\| E9999 | not in A.3 | x |
        \\## A.3 Registry
        \\### Lexical (E01xx)
        \\| Code | Meaning | § |
        \\|------|---------|---|
        \\| E0101 | invalid UTF-8 in source | 2.1 |
        \\| E0102 | stray carriage return | 2.1 |
        \\### Warnings
        \\| W0101 | doc comment documents nothing | 2.8 |
        \\
        \\Implementations may add warnings with codes `W9xxx`.
    );
    try std.testing.expectEqual(@as(usize, 3), codes.len);
    try std.testing.expectEqualStrings("W0101", codes[2]);

    const cov: Coverage = try .init(arena.allocator(), codes);
    cov.add(cov.fail, "E0101");
    cov.add(cov.pass, "E0101");
    cov.add(cov.fail, "E0102");
    cov.add(cov.fail, "W9001");
    var out: Writer.Allocating = .init(arena.allocator());
    try cov.writeLacking(&out.writer);
    try std.testing.expectEqualStrings(
        \\coverage: 2 of 3 A.3 codes lack a passing or failing case
        \\  E0102  missing pass
        \\  W0101  missing pass, fail
        \\
    , out.written());
}
